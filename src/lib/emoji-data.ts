/** 悬停消息时展示的快捷回应 */
export const QUICK_REACTIONS = ['👍', '❤️', '😂', '🎉', '👀', '🚀']

/** 解析成 `{ char, keywords }`,结果做缓存避免重复计算 */
const parsedCache = new Map<string, { char: string; keywords: string }>()

export function parseEmojiEntry(entry: string): { char: string; keywords: string } {
  const cached = parsedCache.get(entry)
  if (cached) return cached
  const idx = entry.indexOf(' ')
  const parsed =
    idx === -1
      ? { char: entry, keywords: '' }
      : { char: entry.slice(0, idx), keywords: entry.slice(idx + 1).toLowerCase() }
  parsedCache.set(entry, parsed)
  return parsed
}

/** 按关键词过滤。空查询返回全部分组。 */
export function searchEmoji(query: string): EmojiGroup[] {
  const q = query.trim().toLowerCase()
  if (!q) return EMOJI_GROUPS
  return EMOJI_GROUPS.map((g) => ({
    id: g.id,
    wide: g.wide,
    emojis: g.emojis.filter((e) => parseEmojiEntry(e).keywords.includes(q)),
  })).filter((g) => g.emojis.length > 0)
}

/** 统计字符串里的表情个数(用于「纯表情放大」判断) */
export function countEmoji(text: string): number {
  const m = text.match(/\p{Extended_Pictographic}/gu)
  return m ? m.length : 0
}

let segmenter: Intl.Segmenter | null = null

/**
 * 判断条目是否属于「宽条目」(颜文字),需要按文本排版而不是放进方格。
 *
 * 为什么不用「长度」或「有没有图形字符」判断:
 * - `(♥ω♥*)` 含 ♥(U+2665,属于图形表情),但它显然是颜文字;
 * - `ʕ•ᴥ•ʔ` 一个图形字符都没有,但同样是颜文字;
 * - `👨‍👩‍👧` 码点长度 5,却只是「一个」表情。
 * 唯一可靠的信号是**字素簇个数**:单个表情永远是 1,颜文字必然大于 1。
 */
export function isWideEntry(char: string): boolean {
  if (typeof Intl !== 'undefined' && typeof Intl.Segmenter === 'function') {
    segmenter ??= new Intl.Segmenter()
    let n = 0
    for (const _ of segmenter.segment(char)) {
      n++
      if (n > 1) return true
    }
    return false
  }
  // 极旧环境的兜底:按码点长度粗判(会误伤 ZWJ 组合表情,但不影响功能)
  return [...char].length > 2
}

/**
 * 判断消息是否「只由表情和空白组成」。
 *
 * 坑:不能只靠 `\p{Emoji_Component}` 字符类 —— 数字 0-9 和 `#` `*` 也属于
 * Emoji_Component(它们用于组成 1️⃣ 这类键帽),单用字符类会把 "123" 误判成纯表情。
 * 所以额外要求:至少有一个真正的图形表情,或一个完整的键帽序列,且不含 ASCII 字母。
 */
export function isEmojiOnly(text: string): boolean {
  const t = text.trim()
  if (!t) return false
  if (/[A-Za-z]/.test(t)) return false

  const hasPictographic = /\p{Extended_Pictographic}/u.test(t)
  const hasKeycap = /[\d#*]\uFE0F?\u20E3/u.test(t)
  if (!hasPictographic && !hasKeycap) return false

  return /^[\p{Extended_Pictographic}\p{Emoji_Component}\u200d\uFE0F\u20E3\s]+$/u.test(t)
}
